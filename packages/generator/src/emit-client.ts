import type { ValidatedModel, ValidatedSchema } from "@zed-orm/schema";
import type { SqlDialect } from "@zed-orm/query-builder";
import { readDatasourceProvider } from "./read-provider.js";
import { toDelegateName } from "./type-mapping.js";

function driverImport(provider: SqlDialect): {
  packageName: string;
  factoryName: string;
} {
  if (provider === "mysql") {
    return {
      packageName: "@zed-orm/driver-mysql",
      factoryName: "createMysqlDriver",
    };
  }
  return {
    packageName: "@zed-orm/driver-postgres",
    factoryName: "createPostgresDriver",
  };
}

function emitModelTypeImports(models: readonly ValidatedModel[]): string {
  const names = new Set<string>();
  for (const model of models) {
    names.add(model.name);
    names.add(`${model.name}FindManyArgs`);
    names.add(`${model.name}FindFirstArgs`);
    names.add(`${model.name}FindUniqueArgs`);
    names.add(`${model.name}CreateArgs`);
    names.add(`${model.name}CreateManyArgs`);
    names.add(`${model.name}UpdateArgs`);
    names.add(`${model.name}UpdateManyArgs`);
    names.add(`${model.name}DeleteArgs`);
    names.add(`${model.name}DeleteManyArgs`);
  }
  return [...names].sort((left, right) => left.localeCompare(right)).join(", ");
}

function emitDelegateTypeMap(model: ValidatedModel): string {
  return [
    `  {`,
    `    readonly findMany: ${model.name}FindManyArgs;`,
    `    readonly findFirst: ${model.name}FindFirstArgs;`,
    `    readonly findUnique: ${model.name}FindUniqueArgs;`,
    `    readonly create: ${model.name}CreateArgs;`,
    `    readonly createMany: ${model.name}CreateManyArgs;`,
    `    readonly update: ${model.name}UpdateArgs;`,
    `    readonly updateMany: ${model.name}UpdateManyArgs;`,
    `    readonly delete: ${model.name}DeleteArgs;`,
    `    readonly deleteMany: ${model.name}DeleteManyArgs;`,
    `  }`,
  ].join("\n");
}

function emitDelegateTypeAlias(model: ValidatedModel): string {
  return `export type ${model.name}Delegate = ModelDelegate<${model.name}, ${emitDelegateTypeMap(model)}>;`;
}

function emitDelegateInstantiation(
  model: ValidatedModel,
  executorName: string,
  dialect: SqlDialect,
  transactionName?: string,
): string {
  const delegate = toDelegateName(model.name);
  const transactionArg =
    transactionName === undefined
      ? `, "${dialect}"`
      : `, "${dialect}", (callback) => ${transactionName}.transaction((tx) => callback(tx))`;
  return `    ${delegate}: new ModelDelegate(${executorName}, modelMetas[${JSON.stringify(model.name)}], modelMetas${transactionArg}) as ${model.name}Delegate,`;
}

/** Emit the generated client factory and delegate wiring. */
export function emitClient(schema: ValidatedSchema): string {
  const provider = readDatasourceProvider(schema);
  const { packageName, factoryName } = driverImport(provider);

  const models = [...schema.models.values()].sort((left, right) =>
    left.name.localeCompare(right.name),
  );

  const delegateTypeAliases = models.map((model) => emitDelegateTypeAlias(model));
  const delegateLines = models.map((model) =>
    emitDelegateInstantiation(model, "executor", provider),
  );
  const rootDelegateLines = models.map((model) =>
    emitDelegateInstantiation(model, "driver", provider, "driver"),
  );

  const modelDelegateProperties = models.map(
    (model) =>
      `  readonly ${toDelegateName(model.name)}: ${model.name}Delegate;`,
  );

  return [
    "// This file is generated by `zed generate`. Do not edit manually.",
    "",
    `import { ${factoryName} } from "${packageName}";`,
    'import { ModelDelegate, type QueryExecutor, type TransactionClient, withTransaction } from "@zed-orm/runtime";',
    `import { modelMetas } from "./meta.js";`,
    `import type { ${emitModelTypeImports(models)} } from "./types.js";`,
    "",
    ...delegateTypeAliases,
    "",
    "export interface GeneratedClientOptions {",
    "  readonly databaseUrl: string;",
    "}",
    "",
    "export type ModelDelegates = {",
    ...modelDelegateProperties,
    "};",
    "",
    "export interface GeneratedClient extends ModelDelegates {",
    "  connect(): Promise<void>;",
    "  disconnect(): Promise<void>;",
    "  $transaction<TResult>(",
    "    callback: (tx: TransactionClient<ModelDelegates>) => Promise<TResult>,",
    "  ): Promise<TResult>;",
    "}",
    "",
    "function createDelegates(executor: QueryExecutor): ModelDelegates {",
    "  return {",
    ...delegateLines,
    "  };",
    "}",
    "",
    "export function createClient(",
    "  options: GeneratedClientOptions,",
    "): GeneratedClient {",
    `  const driver = ${factoryName}({`,
    "    databaseUrl: options.databaseUrl,",
    "  });",
    "  const { $transaction } = withTransaction(driver, createDelegates);",
    "",
    "  return {",
    ...rootDelegateLines,
    "    async connect() {",
    "      await driver.connect();",
    "    },",
    "    async disconnect() {",
    "      await driver.disconnect();",
    "    },",
    "    $transaction,",
    "  };",
    "}",
    "",
  ].join("\n");
}
