import type { ValidatedSchema } from "@zed-orm/schema";
import { emitClient } from "./emit-client.js";
import { emitMeta } from "./emit-meta.js";
import { emitTypes } from "./emit-types.js";

export interface GeneratedFile {
  readonly path: string;
  readonly content: string;
}

export interface GenerateClientOptions {
  /** Output directory relative path prefix for generated imports. */
  readonly importPrefix?: string;
}

export interface GenerateClientResult {
  readonly files: readonly GeneratedFile[];
}

/**
 * Generate a deterministic TypeScript client from a validated schema.
 */
export function generateClient(
  schema: ValidatedSchema,
  _options: GenerateClientOptions = {},
): GenerateClientResult {
  const files: GeneratedFile[] = [
    { path: "types.ts", content: emitTypes(schema) },
    { path: "meta.ts", content: emitMeta(schema) },
    { path: "client.ts", content: emitClient(schema) },
    {
      path: "index.ts",
      content: [
        "// This file is generated by `zed generate`. Do not edit manually.",
        "",
        'export * from "./types.js";',
        'export * from "./meta.js";',
        'export * from "./client.js";',
        "",
      ].join("\n"),
    },
  ];

  return { files };
}
