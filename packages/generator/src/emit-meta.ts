import { schemaToModelMetas } from "./schema-to-meta.js";
import type {
  GeneratorFieldMeta,
  GeneratorModelMeta,
  GeneratorRelationMeta,
} from "./meta-types.js";
import type { ValidatedSchema } from "@zed-orm/schema";

function serializeFieldMeta(field: GeneratorFieldMeta): string {
  const parts = [
    `name: ${JSON.stringify(field.name)}`,
    `columnName: ${JSON.stringify(field.columnName)}`,
    `isRelation: ${field.isRelation}`,
    `isId: ${field.isId}`,
    `isUnique: ${field.isUnique}`,
    `isList: ${field.isList}`,
  ];

  if (field.scalarKind !== undefined) {
    parts.push(`scalarKind: ${JSON.stringify(field.scalarKind)}`);
  }
  if (field.enumName !== undefined) {
    parts.push(`enumName: ${JSON.stringify(field.enumName)}`);
  }
  if (field.isUpdatedAt === true) {
    parts.push(`isUpdatedAt: true`);
  }

  return `{ ${parts.join(", ")} }`;
}

function serializeRelationMeta(relation: GeneratorRelationMeta): string {
  const parts = [
    `fieldName: ${JSON.stringify(relation.fieldName)}`,
    `relatedModel: ${JSON.stringify(relation.relatedModel)}`,
    `kind: ${JSON.stringify(relation.kind)}`,
    `localFkFields: ${JSON.stringify(relation.localFkFields)}`,
    `foreignKeyFields: ${JSON.stringify(relation.foreignKeyFields)}`,
  ];

  if (relation.onSoftDelete !== undefined) {
    parts.push(`onSoftDelete: ${JSON.stringify(relation.onSoftDelete)}`);
  }

  if (relation.reverseFieldName !== undefined) {
    parts.push(
      `reverseFieldName: ${JSON.stringify(relation.reverseFieldName)}`,
    );
  }

  if (relation.joinTable !== undefined) {
    parts.push(
      `joinTable: { tableName: ${JSON.stringify(relation.joinTable.tableName)}, localColumn: ${JSON.stringify(relation.joinTable.localColumn)}, foreignColumn: ${JSON.stringify(relation.joinTable.foreignColumn)} }`,
    );
  }

  return `{ ${parts.join(", ")} }`;
}

function serializeModelMeta(meta: GeneratorModelMeta): string {
  const fieldEntries = [...meta.fields.entries()]
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([name, field]) => `      [${JSON.stringify(name)}, ${serializeFieldMeta(field)}],`);

  const relationEntries = [...meta.relations.entries()]
    .sort(([left], [right]) => left.localeCompare(right))
    .map(
      ([name, relation]) =>
        `      [${JSON.stringify(name)}, ${serializeRelationMeta(relation)}],`,
    );

  const softDeleteParts =
    meta.softDelete === true
      ? [
          `    softDelete: true,`,
          `    deletedAtField: ${JSON.stringify(meta.deletedAtField ?? "deletedAt")},`,
        ]
      : [];

  return [
    `  ${JSON.stringify(meta.modelName)}: {`,
    `    modelName: ${JSON.stringify(meta.modelName)},`,
    `    tableName: ${JSON.stringify(meta.tableName)},`,
    `    idFields: ${JSON.stringify(meta.idFields)},`,
    ...softDeleteParts,
    `    fields: new Map([`,
    ...fieldEntries,
    `    ] as const),`,
    `    relations: new Map([`,
    ...relationEntries,
    `    ] as const),`,
    `  },`,
  ].join("\n");
}

/** Emit model metadata consumed by the runtime read delegate. */
export function emitMeta(schema: ValidatedSchema): string {
  const metas = schemaToModelMetas(schema);

  const lines = [
    "// This file is generated by `zed generate`. Do not edit manually.",
    "",
    'import type { ModelMeta } from "@zed-orm/query-builder";',
    "",
    "export const modelMetas = {",
    ...metas.map((meta) => serializeModelMeta(meta)),
    "} as const satisfies Record<string, ModelMeta>;",
    "",
  ];

  return lines.join("\n");
}
