import { quoteIdentifier, renderColumnSqlType } from "./dialect.js";
import type {
  MigrationOp,
  MigrationProvider,
  RenderedMigration,
  SnapshotColumn,
  SnapshotDefault,
  SnapshotTable,
} from "./types.js";

function renderDefault(
  provider: MigrationProvider,
  defaultValue: SnapshotDefault,
  columnType: string,
): string {
  if (defaultValue.kind === "literal") {
    if (defaultValue.value === null) {
      return "DEFAULT NULL";
    }
    if (typeof defaultValue.value === "boolean") {
      return `DEFAULT ${defaultValue.value ? "TRUE" : "FALSE"}`;
    }
    if (typeof defaultValue.value === "number") {
      return `DEFAULT ${defaultValue.value}`;
    }
    return `DEFAULT '${String(defaultValue.value).replaceAll("'", "''")}'`;
  }

  switch (defaultValue.name) {
    case "uuid":
      return provider === "postgresql"
        ? "DEFAULT gen_random_uuid()"
        : "DEFAULT (UUID())";
    case "now":
      return "DEFAULT CURRENT_TIMESTAMP";
    case "autoincrement":
      if (provider === "mysql") {
        return "";
      }
      return columnType === "INTEGER" ? "GENERATED BY DEFAULT AS IDENTITY" : "";
    default:
      return "";
  }
}

function hasAutoIncrementDefault(column: SnapshotColumn): boolean {
  return (
    column.default?.kind === "function" && column.default.name === "autoincrement"
  );
}

function renderColumnDefinition(
  provider: MigrationProvider,
  column: SnapshotColumn,
): string {
  const columnTypeSql = renderColumnSqlType(provider, column.type);
  const parts = [quoteIdentifier(provider, column.name), columnTypeSql];

  if (!column.nullable) {
    parts.push("NOT NULL");
  }

  if (provider === "mysql" && hasAutoIncrementDefault(column)) {
    parts.push("AUTO_INCREMENT");
  } else if (column.default !== undefined) {
    const defaultSql = renderDefault(provider, column.default, columnTypeSql);
    if (defaultSql.length > 0) {
      parts.push(defaultSql);
    }
  }

  return parts.join(" ");
}

function renderCreateEnum(
  provider: MigrationProvider,
  name: string,
  values: readonly string[],
): string {
  if (provider === "mysql") {
    return "";
  }

  const renderedValues = values
    .map((value) => `'${value.replaceAll("'", "''")}'`)
    .join(", ");
  return `CREATE TYPE ${quoteIdentifier(provider, name)} AS ENUM (${renderedValues});`;
}

function renderAddEnumValue(
  provider: MigrationProvider,
  enumName: string,
  value: string,
): string {
  if (provider === "mysql") {
    return "";
  }

  return `ALTER TYPE ${quoteIdentifier(provider, enumName)} ADD VALUE '${value.replaceAll("'", "''")}';`;
}

function renderCreateTable(
  provider: MigrationProvider,
  table: SnapshotTable,
): string[] {
  const statements: string[] = [];
  const columnSql = table.columns.map((column) =>
    renderColumnDefinition(provider, column),
  );

  if (table.primaryKey.length > 0) {
    const pkColumns = table.primaryKey
      .map((name) => quoteIdentifier(provider, name))
      .join(", ");
    columnSql.push(`PRIMARY KEY (${pkColumns})`);
  }

  statements.push(
    `CREATE TABLE ${quoteIdentifier(provider, table.name)} (\n  ${columnSql.join(",\n  ")}\n);`,
  );

  for (const unique of table.uniqueConstraints) {
    statements.push(renderAddUnique(provider, table.name, unique));
  }

  for (const index of table.indexes) {
    statements.push(renderCreateIndex(provider, table.name, index));
  }

  for (const foreignKey of table.foreignKeys) {
    statements.push(renderAddForeignKey(provider, table.name, foreignKey));
  }

  return statements;
}

function renderAddColumn(
  provider: MigrationProvider,
  tableName: string,
  column: SnapshotColumn,
): string {
  return `ALTER TABLE ${quoteIdentifier(provider, tableName)} ADD COLUMN ${renderColumnDefinition(provider, column)};`;
}

function renderDropColumn(
  provider: MigrationProvider,
  tableName: string,
  columnName: string,
): string {
  return `ALTER TABLE ${quoteIdentifier(provider, tableName)} DROP COLUMN ${quoteIdentifier(provider, columnName)};`;
}

function renderAlterColumn(
  provider: MigrationProvider,
  tableName: string,
  to: SnapshotColumn,
): string {
  if (provider === "mysql") {
    return `ALTER TABLE ${quoteIdentifier(provider, tableName)} MODIFY COLUMN ${renderColumnDefinition(provider, to)};`;
  }

  const typeSql = renderColumnSqlType(provider, to.type);
  const nullSql = to.nullable ? "DROP NOT NULL" : "SET NOT NULL";
  const usingClause =
    to.type.kind === "enum"
      ? ` USING ${quoteIdentifier(provider, to.name)}::${quoteIdentifier(provider, to.type.enumName)}`
      : "";

  return `ALTER TABLE ${quoteIdentifier(provider, tableName)} ALTER COLUMN ${quoteIdentifier(provider, to.name)} TYPE ${typeSql}${usingClause}, ALTER COLUMN ${quoteIdentifier(provider, to.name)} ${nullSql};`;
}

function renderCreateIndex(
  provider: MigrationProvider,
  tableName: string,
  index: { name: string; columns: readonly string[] },
): string {
  const columns = index.columns
    .map((name) => quoteIdentifier(provider, name))
    .join(", ");
  return `CREATE INDEX ${quoteIdentifier(provider, index.name)} ON ${quoteIdentifier(provider, tableName)} (${columns});`;
}

function renderDropIndex(
  provider: MigrationProvider,
  tableName: string,
  indexName: string,
): string {
  if (provider === "mysql") {
    return `DROP INDEX ${quoteIdentifier(provider, indexName)} ON ${quoteIdentifier(provider, tableName)};`;
  }

  return `DROP INDEX ${quoteIdentifier(provider, indexName)};`;
}

function renderAddUnique(
  provider: MigrationProvider,
  tableName: string,
  unique: { name: string; columns: readonly string[] },
): string {
  const columns = unique.columns
    .map((name) => quoteIdentifier(provider, name))
    .join(", ");
  return `ALTER TABLE ${quoteIdentifier(provider, tableName)} ADD CONSTRAINT ${quoteIdentifier(provider, unique.name)} UNIQUE (${columns});`;
}

function renderDropUnique(
  provider: MigrationProvider,
  tableName: string,
  constraintName: string,
): string {
  if (provider === "mysql") {
    return `ALTER TABLE ${quoteIdentifier(provider, tableName)} DROP INDEX ${quoteIdentifier(provider, constraintName)};`;
  }

  return `ALTER TABLE ${quoteIdentifier(provider, tableName)} DROP CONSTRAINT ${quoteIdentifier(provider, constraintName)};`;
}

function renderAddForeignKey(
  provider: MigrationProvider,
  tableName: string,
  foreignKey: {
    name: string;
    columns: readonly string[];
    referencedTable: string;
    referencedColumns: readonly string[];
  },
): string {
  const columns = foreignKey.columns
    .map((name) => quoteIdentifier(provider, name))
    .join(", ");
  const referencedColumns = foreignKey.referencedColumns
    .map((name) => quoteIdentifier(provider, name))
    .join(", ");
  return `ALTER TABLE ${quoteIdentifier(provider, tableName)} ADD CONSTRAINT ${quoteIdentifier(provider, foreignKey.name)} FOREIGN KEY (${columns}) REFERENCES ${quoteIdentifier(provider, foreignKey.referencedTable)} (${referencedColumns});`;
}

function renderDropForeignKey(
  provider: MigrationProvider,
  tableName: string,
  constraintName: string,
): string {
  if (provider === "mysql") {
    return `ALTER TABLE ${quoteIdentifier(provider, tableName)} DROP FOREIGN KEY ${quoteIdentifier(provider, constraintName)};`;
  }

  return `ALTER TABLE ${quoteIdentifier(provider, tableName)} DROP CONSTRAINT ${quoteIdentifier(provider, constraintName)};`;
}

function renderOperation(
  provider: MigrationProvider,
  operation: MigrationOp,
): string | string[] {
  switch (operation.op) {
    case "createEnum":
      return renderCreateEnum(provider, operation.name, operation.values);
    case "addEnumValue":
      return renderAddEnumValue(provider, operation.enumName, operation.value);
    case "createTable":
      return renderCreateTable(provider, operation.table);
    case "dropTable":
      return `DROP TABLE ${quoteIdentifier(provider, operation.tableName)};`;
    case "addColumn":
      return renderAddColumn(provider, operation.tableName, operation.column);
    case "dropColumn":
      return renderDropColumn(provider, operation.tableName, operation.columnName);
    case "alterColumn":
      return renderAlterColumn(provider, operation.tableName, operation.to);
    case "createIndex":
      return renderCreateIndex(provider, operation.tableName, operation.index);
    case "dropIndex":
      return renderDropIndex(
        provider,
        operation.tableName,
        operation.indexName,
      );
    case "addUnique":
      return renderAddUnique(provider, operation.tableName, operation.unique);
    case "dropUnique":
      return renderDropUnique(
        provider,
        operation.tableName,
        operation.constraintName,
      );
    case "addForeignKey":
      return renderAddForeignKey(
        provider,
        operation.tableName,
        operation.foreignKey,
      );
    case "dropForeignKey":
      return renderDropForeignKey(
        provider,
        operation.tableName,
        operation.constraintName,
      );
    default:
      return "";
  }
}

/** Render migration operations as SQL for the snapshot provider. */
export function renderMigration(
  provider: MigrationProvider,
  operations: readonly MigrationOp[],
): RenderedMigration {
  const statements: string[] = [];

  for (const operation of operations) {
    const rendered = renderOperation(provider, operation);
    if (Array.isArray(rendered)) {
      statements.push(...rendered);
    } else if (rendered.length > 0) {
      statements.push(rendered);
    }
  }

  const sql = statements.length > 0 ? `${statements.join("\n\n")}\n` : "";
  return { sql, statements };
}
